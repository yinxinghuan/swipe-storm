import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = path.join(ROOT, 'src/SwipeStorm/cartridge/generated.ts');

function parseArgs(argv) {
  const out = { sentence: '', activate: true, json: false };
  for (let i = 0; i < argv.length; i += 1) {
    const key = argv[i];
    const next = argv[i + 1];
    if (key === '--sentence' && next) out.sentence = argv[++i];
    else if (key === '--activate') out.activate = true;
    else if (key === '--no-activate' || key === '--dry-run') out.activate = false;
    else if (key === '--json') out.json = true;
    else if (key === '-h' || key === '--help') usage(0);
  }
  if (!out.sentence) usage(1);
  return out;
}

function usage(code) {
  const msg = [
    'Usage:',
    '  node scripts/gen-cartridge.mjs --sentence "approve wizard school applications" [--no-activate] [--json]',
    '',
    'This is a conservative rule-based generator for Swipe Storm decision-card cartridges.',
    'It writes and locally activates theme=generated by default.',
    'Use --no-activate (or --dry-run) to inspect output without writing.',
  ].join('\n');
  (code ? console.error : console.log)(msg);
  process.exit(code);
}

function hashText(value) {
  let hash = 2166136261;
  for (const ch of value) {
    hash ^= ch.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(36).slice(0, 6);
}

function includesAny(text, words) {
  return words.some((word) => text.includes(word.toLowerCase()));
}

