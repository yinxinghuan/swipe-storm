function item(kind, title, subtitle, body, tags, icon, seal, accent) {
  return { kind, title, subtitle, body, tags, icon, seal, accent };
}

function generate(sentence) {
  const text = sentence.toLowerCase();
  if (includesAny(text, ['potion', 'elixir', 'brew', 'fake or real', 'real or fake', '真假', '鉴定', '药水', '魔药'])) {
    return { family: 'potion-check', cartridge: potion(sentence) };
  }
  if (includesAny(text, ['recycle', 'trash', 'waste', 'garbage', 'sort', 'sorting', 'bin', '垃圾', '分类', '回收', '分拣'])) {
    return { family: 'recycle-sort', cartridge: recycle(sentence) };
  }
  if (includesAny(text, ['academy', 'admission', 'application', 'approve', 'reject', 'wizard', '申请', '审核', '录取', '学院', '通过', '拒绝'])) {
    return { family: 'wizard-academy', cartridge: wizard(sentence) };
  }
  return { family: 'generic-review', cartridge: generic(sentence) };
}

function serialize(cartridge) {
  return [
    "import type { SwipeStormCartridge } from './index';",
    '',
    `export const generatedCartridge: SwipeStormCartridge | null = ${JSON.stringify(cartridge, null, 2)};`,
    '',
  ].join('\n');
}

const args = parseArgs(process.argv.slice(2));
const result = generate(args.sentence);

if (args.activate) {
  fs.writeFileSync(OUT_FILE, serialize(result.cartridge));
}

const payload = {
  sentence: args.sentence,
  family: result.family,
  theme: 'generated',
  activated: args.activate,
  file: OUT_FILE,
  preview: 'http://127.0.0.1:5190/?theme=generated',
  cartridge: result.cartridge,
};

if (args.json) {
  console.log(JSON.stringify(payload, null, 2));
} else {
  console.log(`Generated Swipe Storm cartridge: ${result.family}`);
  console.log(`Theme: ${payload.theme}`);
  if (args.activate) console.log(`Wrote: ${OUT_FILE}`);
  else console.log('Dry run only. Remove --no-activate to write generated.ts.');
  console.log(`Open exactly: ${payload.preview}`);
}
